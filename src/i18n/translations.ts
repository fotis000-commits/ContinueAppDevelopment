// Use English as fallback for languages without full translations
const fallback = (lang: Language): Translations => {
  const maps: Partial<Record<Language, Translations>> = { en, el, es, fr, ar, ja };
  return maps[lang] || en;
};

export function getTranslations(lang: Language): Translations {
  const map = fallback(lang);
  // Merge with English to fill missing keys
  return { ...en, ...map };
}

export function t(translations: Translations, key: string, vars?: Record<string, string | number>): string {
  let text = translations[key] ?? key;
  if (vars) {
    Object.entries(vars).forEach(([k, v]) => {
      text = text.replace(`{${k}}`, String(v));
    });
  }
  return text;
}
